#!/usr/bin/env python3
"""Generate the lc520 kernel patch (LC 520, LC 550, Color Classic II) for an A/UX kernel
(/unix or /etc/config.d/newunix).

  kernel-patch.py KERNEL ld                 kernel-specific link symbols (boardinit_switch)
  kernel-patch.py KERNEL spec ELF BIN BIN2  tools/binpatch.py spec, for /unix and newunix

The patch is the code linked by patches/lc520/build.sh: the Sonora module (src/lc520.S with
modules/sonora) over orwellsize and memcdjsize in pstart, with the call sites
modules/sonora/sites.py redirects to it, and the Cuda transport (modules/cuda/cuda.c) after
the jmp sonora_cegret at cEgretDispatch, with the stubs modules/cuda/sites.py puts at the
Egret driver's entry points.

Sites are found by symbol and instruction pattern (tools/kpatch.py). autoconfig rewrites
only configuration data, so /unix and the newunix it is linked from take the same patch.
"""
import os, sys

here = os.path.dirname(os.path.abspath(__file__))
sys.path[:0] = [os.path.join(here, '..', '..', 'tools'), os.path.join(here, '..', '..', 'modules')]
from kpatch import Kernel, elf_symbols, emit  # noqa: E402
from cuda import sites as cuda  # noqa: E402
from sonora import sites as sonora  # noqa: E402


def main():
    k, cmd = Kernel(sys.argv[1]), sys.argv[2]
    if cmd == 'ld':
        print('boardinit_switch = 0x%08x;' % k.boardinit_switch()[1])
        return
    esym = elf_symbols(sys.argv[3])
    blob, blob2 = open(sys.argv[4], 'rb').read(), open(sys.argv[5], 'rb').read()
    print('; lc520 kernel patch (LC 520, LC 550, Color Classic II), generated by')
    print('; patches/lc520/kernel-patch.py from %s' % os.path.basename(sys.argv[1]))
    print('; Apply with tools/binpatch.py; /unix and the newunix autoconfig links it from.')
    print('file /unix /etc/config.d/newunix')
    emit(k, sonora.sites(k, esym, blob, 'Sonora hooks') + [
        cuda.code(k, esym, blob2, k.sym['cEgretDispatch'] + 6, 'Cuda transport'),
    ] + cuda.stubs(k, esym))
    ckpt = sonora.ckpt_sites(k, esym)
    if ckpt:
        print()
        print('; checkpoint build: hold a checkpoint key through "Launching" to restart there')
        print('file /unix')
        emit(k, ckpt)


if __name__ == '__main__':
    main()
